async function generate(messages, temperature = 0.95) {
  const response = await fetch(localUrl, {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      config,
      temperature,
      messages
    })
  });

  const data = await response.json();
  if (!response.ok) {
    throw new Error(data.error || "Unknown error");
  }

  return data.text || "";
}

let markdown = `# 评估记录\n\n生成时间：${new Date().toLocaleString("zh-CN", { hour12: false })}\n\n`;

for (const suite of suites) {
  markdown += `## ${suite.name}\n\n`;

  for (const example of suite.examples) {
    markdown += `### ${example.label}\n\n`;

    for (const [title, system, user] of example.blocks) {
      const text = await generate(
        [
          { role: "system", content: system },
          { role: "user", content: user }
        ],
        0.95
      );

      markdown += `#### ${title}\n\n${text}\n\n`;
    }
  }
}

const outputDir = path.join(process.cwd(), "docs", "evaluation");
await mkdir(outputDir, { recursive: true });
const outputPath = path.join(outputDir, `evaluation-${new Date().toISOString().slice(0, 10)}.md`);
await writeFile(outputPath, markdown, "utf8");

